import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
const root = new URL('../', import.meta.url);
const inventory = JSON.parse(readFileSync(new URL('analytics_runtime/engine/inventory.json', root), 'utf8'));
for (const entry of inventory) {
  const actual = createHash('sha256').update(readFileSync(new URL('analytics_runtime/engine/' + entry.path, root))).digest('hex');
  if (actual !== entry.sha256) throw new Error(`Analytics engine inventory mismatch: ${entry.path}. Re-sync and review the engine before building.`);
}
const names = ['api/analytics_runtime.py', 'analytics_runtime/engine/inventory.json',
  ...readdirSync(new URL('analytics_runtime/', root)).filter(name => name.endsWith('.py')).map(name => `analytics_runtime/${name}`),
  ...readdirSync(new URL('analytics_runtime/web/', root)).filter(name => /\.(js|html)$/.test(name)).map(name => `analytics_runtime/web/${name}`)].sort();
const hash = createHash('sha256');
for (const name of names) { hash.update(name + '\0'); hash.update(readFileSync(new URL(name, root))); }
writeFileSync(new URL('lib/hospital-analytics/version.ts', root), `// Generated by scripts/analytics-version.mjs at build time.\nexport const ENGINE_VERSION = '${hash.digest('hex')}';\n`);
